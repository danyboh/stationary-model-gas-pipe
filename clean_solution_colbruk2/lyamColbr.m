function lyamda = lyamColbr(Re, Rsh)
% Коефіцієнт гідравлічного опору за рівнянням Колбрука-Уайта
% (перехідна та квадратична області опору)
%   Re  - число Рейнольдса
%   Rsh - абсолютна еквівалентна шорсткість, м (необов'язковий)
% Джерела: Idelchik I.E. Handbook of Hydraulic Resistance,
%          4th ed., Begell House, 2007, с. 94, рівн. (2.9);
%          Haaland S.E. // J. Fluids Eng., 1983, 105(1), 89-90

    Dvn = 1.388;                    % m, внутрішній діаметр газопроводу
    if nargin < 2
        Rsh = 0.0002;               % m, еквівалентна шорсткість
    end

    dr = Rsh / Dvn;                 % відносна шорсткість

    % явна апроксимація Хааланда (початкове наближення)
    lyamda = (-1.8*log10((dr/3.7).^1.11 + 6.9./Re)).^(-2);

    % уточнення до точного розв'язку рівняння Колбрука-Уайта
    for it = 1:4
        lyamda = (-2*log10(dr/3.7 + 2.51./(Re.*sqrt(lyamda)))).^(-2);
    end
end