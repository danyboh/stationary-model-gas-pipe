function out = bm_moc(gas, bc, dx, tOut)
%BM_MOC Еталон: повна ізотермічна система руху газу, метод характеристик.
%
% =========================================================================
%  МАТЕМАТИЧНА МОДЕЛЬ
% =========================================================================
%  Рівняння руху (3.11) базового тексту ДО відкидання інерційного члена
%  d(rho*u)/dt і рівняння нерозривності (3.20), записані через масову
%  витрату q = rho*u*S та c^2 = p/rho:
%
%    dp/dt + (c^2/S)*dq/dx = 0                                  нерозривність
%    dq/dt + S*dp/dx + lam*c^2*q*|q|/(2*D*S*p) = 0              рух
%
%  Інерційний член dq/dt збережено - саме його відкидає параболічна
%  модель. Конвективний член d(rho*u^2)/dx відкинуто: його відношення до
%  dp/dx має порядок u^2/c^2 ~ 6e-4.
%
%  Коефіцієнт тертя lam - за Колбруком-Уайтом (lyamColbr) з локального Re.
%
% =========================================================================
%  ХАРАКТЕРИСТИКИ  dx/dt = +c  і  dx/dt = -c
% =========================================================================
%    C+ :  dq + (S/c)*dp + F*dt = 0
%    C- :  dq - (S/c)*dp + F*dt = 0,        F = lam*c^2*q*|q|/(2*D*S*p)
%
% =========================================================================
%  РІЗНИЦЕВА ФОРМА  (dt = dx/c, тертя за правилом трапецій)
% =========================================================================
%    Cp = q(i-1) + (S/c)*p(i-1) - dt/2*F(i-1)
%    Cm = q(i+1) - (S/c)*p(i+1) - dt/2*F(i+1)
%
%    p(i)_new = (Cp - Cm) / (2*S/c)
%    q(i)_new = (Cp + Cm) / (2 + dt*K(i)*|q(i)|),   K = lam*c^2/(2*D*S*p(i)_new)
%
%  Межі:  x = 0 - заданий тиск, витрата з характеристики C-;
%         x = L - задана витрата, тиск з характеристики C+.
%
%  Тертя за трапеціями дає другий порядок; при явному терті в точках
%  сходу характеристик схема має перший порядок і дрейфує на сталому
%  режимі.
%
% =========================================================================
%  ВИКЛИК
% =========================================================================
%    out = bm_moc(gas, bc, dx, tOut)
%
%    gas.L, gas.D, gas.S   - довжина, м; внутрішній діаметр, м; площа, м^2
%    gas.c2                - c^2 = Z*R*T/M, м^2/с^2
%    gas.mu                - динамічна в'язкість, Па*с
%    gas.Rsh               - еквівалентна шорсткість, м
%    bc.t                  - час граничних даних, с
%    bc.p0                 - тиск на вході, Па
%    bc.qL                 - масова витрата на виході, кг/с
%    dx                    - крок сітки, м
%    tOut                  - моменти виводу, с
%
%    out.x, out.t          - сітка, м; моменти виводу, с
%    out.p, out.q          - поле тиску, Па, і витрати, кг/с (nx x numel(tOut))
%    out.p0, out.pL        - тиск на вході й виході, Па
%    out.q0, out.qL        - витрата на вході й виході, кг/с

L  = gas.L;
D  = gas.D;
S  = gas.S;
c2 = gas.c2;
c  = sqrt(c2);

nx = round(L/dx) + 1;
dx = L/(nx - 1);
x  = (0:nx-1)'*dx;
dt = dx/c;                          % число Куранта = 1: характеристики йдуть у вузли
T  = bc.t(end) - bc.t(1);
nt = ceil(T/dt);
SC = S/c;

lamOf = @(q) lyamColbr(max(4*abs(q)/(pi*D*gas.mu), 4000), gas.Rsh);

% --- початковий стан: стаціонарний розв'язок при граничних умовах у t0 ---
p0i  = bc.p0(1);
qi   = bc.qL(1);
lam0 = lamOf(qi);
p    = sqrt(p0i^2 - lam0*c2*qi^2*x/(D*S^2));
q    = qi*ones(nx, 1);

% --- вивід ---
tOut = tOut(:);
nOut = numel(tOut);
P    = zeros(nx, nOut);
Qf   = zeros(nx, nOut);
tPrev = bc.t(1);
k = 1;
while k <= nOut && tOut(k) <= tPrev
    P(:,k)  = p;
    Qf(:,k) = q;
    k = k + 1;
end

ii = 2:nx-1;

for n = 1:nt
    tn = bc.t(1) + n*dt;

    lam = lamOf(q);
    F   = lam.*c2.*q.*abs(q)./(2*D*S*p);

    % --- внутрішні вузли ---
    Cp = q(ii-1) + SC*p(ii-1) - 0.5*dt*F(ii-1);
    Cm = q(ii+1) - SC*p(ii+1) - 0.5*dt*F(ii+1);

    pn = zeros(nx, 1);
    qn = zeros(nx, 1);
    pn(ii) = (Cp - Cm)/(2*SC);
    K      = lam(ii)*c2./(2*D*S*pn(ii));
    qn(ii) = (Cp + Cm)./(2 + dt*K.*abs(q(ii)));

    % --- вхід: заданий тиск, витрата з C- ---
    pn(1) = interp1(bc.t, bc.p0, min(tn, bc.t(end)));
    K1    = lam(1)*c2/(2*D*S*pn(1));
    qn(1) = (q(2) + SC*(pn(1) - p(2)) - 0.5*dt*F(2)) / (1 + 0.5*dt*K1*abs(q(1)));

    % --- вихід: задана витрата, тиск з C+ ---
    qn(nx) = interp1(bc.t, bc.qL, min(tn, bc.t(end)));
    base   = q(nx-1) + SC*p(nx-1) - 0.5*dt*F(nx-1) - qn(nx);
    KL     = lam(nx)*c2/(2*D*S);
    pl     = p(nx);
    for it = 1:3
        pl = (base - 0.5*dt*KL*qn(nx)*abs(qn(nx))/pl)/SC;
    end
    pn(nx) = pl;

    % --- вивід з лінійною інтерполяцією між часовими шарами ---
    while k <= nOut && tOut(k) <= tn
        w = (tOut(k) - tPrev)/dt;
        P(:,k)  = (1 - w)*p + w*pn;
        Qf(:,k) = (1 - w)*q + w*qn;
        k = k + 1;
    end

    p = pn;
    q = qn;
    tPrev = tn;
end

out.x    = x;
out.t    = tOut;
out.p    = P;
out.q    = Qf;
out.p0   = P(1,:)';
out.pL   = P(nx,:)';
out.q0   = Qf(1,:)';
out.qL   = Qf(nx,:)';
out.dx   = dx;
out.dt   = dt;
out.nx   = nx;
out.nt   = nt;
out.c    = c;
out.lam0 = lam0;

end
